"""Compose complete revisions while retaining per-distribution file ownership."""

import json
import os
import shutil
from contextlib import contextmanager
from pathlib import Path, PurePosixPath
from typing import Dict, Iterable, Iterator, Sequence

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.specifiers import SpecifierSet
from packaging.utils import canonicalize_name, parse_wheel_filename

from distman.install import InstallError
from distman.install.models import Addition, FileDigest, InstalledArtifact, InstallState
from distman.install.targets import Target
from distman.install.wheels import sha256

MANIFEST = ".distman-install.json"


def inventory(directory: Path) -> Dict[str, FileDigest]:
    """Inventory payload bytes and modes, excluding receipts and generated bytecode.

    :param directory: Import root or composed revision to scan recursively.
    :return: Relative file paths mapped to SHA-256 digests and permission modes.
    :raises InstallError: If a payload contains an unexpected symbolic link.
    """
    result = {}
    for path in sorted(directory.rglob("*")):
        if "__pycache__" in path.parts:
            continue
        if path.is_symlink():
            raise InstallError(f"Unexpected link in installed payload: {path}")
        if path.is_file() and path != directory / MANIFEST:
            result[path.relative_to(directory).as_posix()] = {
                "sha256": sha256(path),
                "mode": path.stat().st_mode & 0o777,
            }
    return result


def read_state(destination: Path) -> InstallState:
    """Read an owned revision and reject unsafe paths, corruption, or foreign files.

    :param destination: Active managed symlink whose receipt and payload should be verified.
    :return: Verified receipt, or an empty initial state when the destination does not exist.
    :raises InstallError: If ownership metadata is invalid or installed contents differ from the
        receipt.
    """
    if not os.path.lexists(destination):
        return {"schema": 1, "artifacts": {}}
    if not destination.is_symlink() or not (destination / MANIFEST).is_file():
        raise InstallError(f"Refusing unmanaged destination: {destination}")
    try:
        state = json.loads((destination / MANIFEST).read_text())
        if state["schema"] != 1 or not isinstance(state["artifacts"], dict):
            raise ValueError("unsupported schema")
        expected = {}
        for record in state["artifacts"].values():
            for name, checksum in record["files"].items():
                path = PurePosixPath(name)
                if path.is_absolute() or ".." in path.parts or "\\" in name or ":" in name:
                    raise ValueError("invalid ownership path")
                if name in expected:
                    raise ValueError("duplicate file ownership")
                expected[name] = checksum
        if expected != inventory(destination):
            raise InstallError(f"Installed content changed or is incomplete: {destination}")
        return state
    except (ValueError, KeyError, TypeError) as exc:
        raise InstallError(f"Invalid ownership metadata in {destination}: {exc}") from exc


def compose(destination: Path, staged: Path, additions: Sequence[Addition]) -> InstallState:
    """Merge all selected wheels in a target, never editing its active revision.

    :param destination: Active managed target to use as the prior revision, if present.
    :param staged: New temporary directory in which to assemble the complete proposed revision.
    :param additions: Ownership key, staged payload, selection receipt, and relative prefix for
        each wheel.
    :return: Complete receipt written inside the proposed revision.
    :raises InstallError: If prior integrity validation fails or added paths conflict with other
        owners.
    """
    state = read_state(destination)
    if destination.exists():
        shutil.copytree(destination, staged, ignore=shutil.ignore_patterns("__pycache__"))
    else:
        staged.mkdir()
    records = state["artifacts"]
    # Remove all replaced artifacts first: coordinated upgrades may transfer paths.
    for key, _, _, _ in additions:
        previous = records.pop(key, None)
        if previous:
            for name in previous["files"]:
                (staged / name).unlink()
    owners = {name: key for key, record in records.items() for name in record["files"]}
    for key, payload, provenance, prefix in additions:
        if (payload / MANIFEST).exists():
            raise InstallError(f"Wheel contains reserved metadata path: {MANIFEST}")
        files = inventory(payload)
        mapped = {}
        for name, checksum in files.items():
            relative = (prefix / name).as_posix()
            path = staged / relative
            if relative == MANIFEST or relative in owners or path.is_file():
                raise InstallError(f"File ownership conflict at {destination / relative}")
            try:
                path.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(payload / name, path)
            except (FileExistsError, IsADirectoryError) as exc:
                raise InstallError(f"File/directory ownership conflict: {path}") from exc
            owners[relative] = key
            mapped[relative] = checksum
        records[key] = InstalledArtifact(**provenance, files=mapped)
    # Prune directories left by obsolete files, but never touch unowned content.
    for path in sorted(staged.rglob("*"), key=lambda p: len(p.parts), reverse=True):
        if path.is_dir() and not any(path.iterdir()):
            path.rmdir()
    (staged / MANIFEST).write_text(json.dumps(state, indent=2, sort_keys=True) + "\n")
    return state


def same_state(destination: Path, state: InstallState) -> bool:
    """Verify active contents and compare their receipt with the proposed revision.

    :param destination: Active managed target whose integrity must still be valid.
    :param state: Proposed complete revision receipt to compare with the active receipt.
    :return: True if the destination exists and its verified receipt equals the proposed state.
    :raises InstallError: If active ownership or file integrity validation fails.
    """
    return destination.exists() and read_state(destination) == state


def marker_environment(target: Target) -> Dict[str, str]:
    """Construct the target marker values known without executing its interpreter.

    :param target: Runtime supplying the known OS, architecture, and Python marker values.
    :return: Packaging marker environment with known runtime fields overridden.
    """
    environment = default_environment()
    environment.update(
        python_version=target.python,
        python_full_version=target.python + ".0",
        implementation_name="cpython",
        implementation_version=target.python + ".0",
        platform_python_implementation="CPython",
        platform_machine="AMD64" if target.platform == "windows" else target.arch,
        sys_platform={"linux": "linux", "windows": "win32", "darwin": "darwin"}[target.platform],
        platform_system={"linux": "Linux", "windows": "Windows", "darwin": "Darwin"}[
            target.platform
        ],
        os_name="nt" if target.platform == "windows" else "posix",
        extra="",
    )
    return environment


def check_script_pairs(records: Iterable[InstalledArtifact]) -> None:
    """Require paired library/script receipts to describe the same wheel revision.

    :param records: Proposed and retained artifacts from all affected roots.
    :return: None.
    :raises InstallError: If independently rolled-back roots disagree or a component is missing.
    """
    pairs = {}
    for record in records:
        if not record.get("separate_scripts"):
            continue
        identity = (record["name"], record["library_path"], record["scripts_path"])
        pairs.setdefault(identity, {})[record["component"]] = record
    for identity, components in pairs.items():
        library = components.get("library")
        scripts = components.get("scripts")
        if not library or not scripts or library["sha256"] != scripts["sha256"]:
            raise InstallError(
                f"Library and scripts revisions disagree for {identity[0]}; "
                "restore matching revisions or reinstall the affected package"
            )


def check_dependencies(records: Iterable[InstalledArtifact], target: Target) -> None:
    """Reject broken base dependencies, including retained shared distributions.

    Pip still owns resolution. This guard detects host-marker omissions during
    cross downloads rather than claiming pip resolves a foreign environment.

    :param records: Proposed and retained artifact receipts participating in dependency
        validation.
    :param target: Runtime for evaluating compatibility and base dependency markers.
    :return: None.
    :raises InstallError: If a dependency is missing/incompatible or a required OS marker is
        unknown.
    """
    selected = {}
    for record in records:
        if record.get("component") == "scripts":
            continue
        if record.get("pure") or target.label in record["targets"]:
            selected[record["name"]] = record
    for record in selected.values():
        if record["pure"]:
            tags = parse_wheel_filename(record["wheel"])[3]
            if not tags & target.tags or not SpecifierSet(record["requires_python"]).contains(
                target.python + ".0", prereleases=True
            ):
                raise InstallError(f"Shared {record['name']} is incompatible with {target.label}")
        for text in record["requires_dist"]:
            requirement = Requirement(text)
            if requirement.marker:
                if any(
                    x in str(requirement.marker) for x in ("platform_release", "platform_version")
                ):
                    raise InstallError(f"Cannot evaluate target OS release marker: {text}")
                if not requirement.marker.evaluate(marker_environment(target)):
                    continue
            dependency = selected.get(canonicalize_name(requirement.name))
            if dependency is None or not requirement.specifier.contains(
                dependency["version"], prereleases=True
            ):
                raise InstallError(f"{record['name']} requires {text} for {target.label}")


@contextmanager
def locks(destinations: Iterable[Path], dryrun: bool = False) -> Iterator[None]:
    """Serialize writers in deterministic order; dry runs create no lock directories.

    :param destinations: Active target paths whose sibling lock directories serialize
        installation.
    :param dryrun: If True, yield without creating parent or lock directories.
    :yields: None while all requested writer locks are held.
    :raises InstallError: If a target already has an active or stale lock directory.
    """
    acquired = []
    try:
        if not dryrun:
            for destination in sorted(destinations):
                destination.parent.mkdir(parents=True, exist_ok=True)
                lock = destination.with_name(f".{destination.name}.install-lock")
                try:
                    lock.mkdir()
                except FileExistsError as exc:
                    raise InstallError(
                        f"Deployment lock exists; inspect before removing: {lock}"
                    ) from exc
                acquired.append(lock)
        yield
    finally:
        for lock in reversed(acquired):
            lock.rmdir()
