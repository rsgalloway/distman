"""Filesystem content hashing independent of package acquisition."""

import hashlib
import os
import stat
from pathlib import Path
from typing import Dict, Iterable, Optional, TypedDict


class FileDigest(TypedDict):
    """Content digest and permission bits for a relative file.

    :ivar sha256: SHA-256 digest of file contents.
    :ivar mode: Permission bits masked to 0o777.
    """

    sha256: str
    mode: int


def sha256(path: Path) -> str:
    """Hash file bytes incrementally without loading the entire artifact into memory.

    :param path: File whose bytes will be hashed.
    :return: Lowercase hexadecimal SHA-256 digest.
    :raises OSError: If the file cannot be read.
    """
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def file_mode(path: Path, windows: Optional[bool] = None) -> int:
    """Return portable permission bits for an inventoried file.

    Windows derives execute bits from the observed filename extension. An active
    ``.exe`` link and its suffixed immutable revision can therefore report
    different modes despite selecting the same file. Preserve meaningful
    read/write state while discarding those synthetic execute bits on Windows.

    :param path: File whose permission mode will be recorded.
    :param windows: Optional platform override used by focused tests.
    :return: Permission bits suitable for stored integrity comparisons.
    """
    mode = stat.S_IMODE(path.stat().st_mode)
    if os.name == "nt" if windows is None else windows:
        mode &= 0o666
    return mode


def inventory(directory: Path, exclude: Iterable[str] = ()) -> Dict[str, FileDigest]:
    """Inventory payload bytes and modes, excluding receipts and generated bytecode.

    :param directory: Import root or composed revision to scan recursively.
    :param exclude: Root-relative filenames omitted from the inventory.
    :return: Relative file paths mapped to SHA-256 digests and permission modes.
    :raises ValueError: If a payload contains an unexpected symbolic link.
    """
    excluded = set(exclude)
    result = {}
    for path in sorted(directory.rglob("*")):
        relative = path.relative_to(directory)
        if "__pycache__" in relative.parts:
            continue
        if path.is_symlink():
            raise ValueError(f"Unexpected link in installed payload: {path}")
        if path.is_file() and relative.as_posix() not in excluded:
            result[relative.as_posix()] = {
                "sha256": sha256(path),
                "mode": file_mode(path),
            }
    return result
